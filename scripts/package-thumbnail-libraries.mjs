// Regenerate the backend-only ARM64 assets using Node and bsdtar (Windows tar).
// Package hashes come from https://packages.ubuntu.com/<suite>/arm64/<name>/download.
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync, copyFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { gzipSync } from "node:zlib";

const packages = [
  ["vulkan-loader", "v/vulkan-loader/libvulkan1_1.3.204.1-2_arm64.deb", "25859879f5a2c4c0a1800819f34ef2c9b45f7713c8f6c16c703d000ce75ceaf8", "libvulkan.so.1"],
  ["libdrm", "libd/libdrm/libdrm2_2.4.113-2~ubuntu0.22.04.1_arm64.deb", "d61b3eb23638adaed392ae6f48cf9f6ec997d089baecc357663b196c578777b8", "libdrm.so.2"],
  ["zlib", "z/zlib/zlib1g_1.2.11.dfsg-2ubuntu9.2_arm64.deb", "cfd99d1ca41e710fdd3f68bfdc4d36dd24e14377656764f00b215b89cf6976e8", "libz.so.1"],
  ["libzstd", "libz/libzstd/libzstd1_1.4.8+dfsg-3build1_arm64.deb", "0102eb80384c2432c4be819663341a1c4e511d05f13ec1467643696531ec6491", "libzstd.so.1"],
  ["libudev", "s/systemd/libudev1_249.11-0ubuntu3.22_arm64.deb", "ec814eee0c7a398e031ece85d07c0108c16f609fb033d7b77700e9106ce86130", "libudev.so.1"],
];
const assets = [];
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");
const tar = (args) => execFileSync("tar", args, { encoding: "utf8", windowsHide: true });
mkdirSync("docs/native", { recursive: true });
for (const [name, packagePath, expected, filename] of packages) {
  const directory = resolve(".tmp/thumbnail-native", name);
  mkdirSync(directory, { recursive: true });
  const url = "https://ports.ubuntu.com/pool/main/" + packagePath;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${name}: HTTP ${response.status}`);
  const deb = Buffer.from(await response.arrayBuffer());
  if (sha256(deb) !== expected) throw new Error(`${name}: package checksum mismatch`);
  const debPath = join(directory, "package.deb");
  writeFileSync(debPath, deb);
  const data = tar(["-tf", debPath]).trim().split(/\r?\n/).find((entry) => /^data\.tar\.(xz|zst|gz)$/.test(entry));
  if (!data) throw new Error(`${name}: missing data archive`);
  tar(["-xf", debPath, "-C", directory, data]);
  const dataPath = join(directory, data);
  const files = tar(["-tf", dataPath]).trim().split(/\r?\n/);
  const library = files.find((entry) => entry.startsWith("./") && entry.includes("/aarch64-linux-gnu/" + filename + "."));
  const license = files.find((entry) => /^\.\/usr\/share\/doc\/[^/]+\/copyright$/.test(entry));
  if (!library || !license) throw new Error(`${name}: missing library or license`);
  tar(["-xf", dataPath, "-C", directory, library, license]);
  const bytes = readFileSync(join(directory, library));
  assets.push({ filename, sha256: sha256(bytes), gzip: gzipSync(bytes, { level: 9 }).toString("base64") });
  copyFileSync(join(directory, license), `docs/native/${name}-copyright.txt`);
  console.log(`${filename}: ${bytes.length} bytes; ${sha256(bytes)}`);
}
writeFileSync("convex/lib/vulkanLoader.generated.ts",
  "// Generated by scripts/package-thumbnail-libraries.mjs. Backend-only Linux ARM64 libraries.\n" +
  "export const VULKAN_LIBRARIES = " + JSON.stringify(assets) + " as const;\n");
